import fs from 'node:fs';
import path from 'node:path';
import { parsePostSource } from './post-parser.mjs';

const root = process.cwd();
const postsDir = path.join(root, 'src', 'content', 'posts');
const outputPath = path.join(root, 'src', 'content', 'postMetadata.generated.ts');
const imports = [];
const records = [];

for (const folder of fs.readdirSync(postsDir).sort()) {
  const indexPath = path.join(postsDir, folder, 'index.ts');
  if (!fs.existsSync(indexPath)) continue;
  const parsed = parsePostSource(fs.readFileSync(indexPath, 'utf8'), indexPath);
  if (parsed.errors.length) throw new Error(`${folder}: ${parsed.errors.join('; ')}`);

  const record = {};
  for (const field of ['slug', 'title', 'excerpt', 'section', 'publishedAt', 'modifiedAt', 'displayDate', 'status', 'heroAlt', 'cardAlt']) {
    const value = parsed.values.get(field);
    if (value !== undefined) record[field] = value;
  }
  for (const field of ['heroImage', 'cardImage']) {
    const identifier = parsed.identifiers.get(field);
    const filename = identifier ? parsed.imageImports.get(identifier) : undefined;
    if (!filename) continue;
    const importName = `${field}_${imports.length}`;
    imports.push(`import ${importName} from './posts/${folder}/${filename}';`);
    record[field] = { importName };
  }

  const fields = Object.entries(record).map(([key, value]) =>
    `${key}: ${typeof value === 'object' ? value.importName : JSON.stringify(value)}`,
  );
  records.push(`  { ${fields.join(', ')} },`);
}

const output = [
  '// Generated by scripts/generate-post-metadata.mjs. Do not hand-edit.',
  "import type { PostMetadata } from './postTypes';",
  ...imports,
  '',
  'export const postMetadata: PostMetadata[] = [',
  ...records,
  '];',
  '',
].join('\n');

fs.writeFileSync(outputPath, output);
console.log(`Generated lightweight metadata for ${records.length} posts.`);
